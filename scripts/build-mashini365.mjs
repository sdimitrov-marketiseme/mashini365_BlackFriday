import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const repo=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const src=path.join(repo,'campaigns/mashini365');
const read=n=>fs.readFile(path.join(src,n),'utf8');
const [html,css,fonts,products,app]=await Promise.all(['page.html','page.css','fonts.css','products.json','interactions.js'].map(read));
const data=JSON.parse(products);
const payload=JSON.stringify({html,css,fonts,products:data});
const bundle=`/* Mashini365 campaign. Generated by scripts/build-mashini365.mjs. */
(function(script){'use strict';
if(!script || !script.src) return;
const assetBase=new URL('./',script.src).href;
const payload=${payload};
function fail(host,error){
 host.dataset.m365State='error';
 const container=host.shadowRoot||host;
 container.replaceChildren();
 const p=document.createElement('p');p.textContent='Не успяхме да заредим страницата. ';
 const a=document.createElement('a');a.href='https://mashini365.bg/';a.textContent='Разгледайте магазина';p.append(a);
 const button=document.createElement('button');button.type='button';button.textContent='Опитайте отново';button.onclick=()=>mount(host);
 container.append(p,button);console.error('Mashini365 landing:',error);
}
function mount(host){
 if(host.dataset.m365State==='ready'||host.dataset.m365State==='loading')return;
 host.dataset.m365State='loading';
 try{
  let fontStyle=document.getElementById('m365-campaign-fonts');
  if(!fontStyle){fontStyle=document.createElement('style');fontStyle.id='m365-campaign-fonts';fontStyle.textContent=payload.fonts;document.head.append(fontStyle);}
  const root=host.shadowRoot||host.attachShadow({mode:'open'});
  const style=document.createElement('style');style.textContent=payload.css;
  const template=document.createElement('template');template.innerHTML=payload.html.replaceAll('__M365_ASSET_BASE__',assetBase);
  root.replaceChildren(style,template.content.cloneNode(true));
  const esc=s=>String(s).replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;').replaceAll('"','&quot;').replaceAll("'",'&#39;');
  const productData=payload.products.map(p=>({...p,image:p.image.replaceAll('__M365_ASSET_BASE__',assetBase),title:esc(p.title),spec:esc(p.spec),shortTitle:p.shortTitle?esc(p.shortTitle):undefined}));
  ${app}
  root.addEventListener('click',event=>{
   const a=event.composedPath().find(el=>el?.tagName==='A');if(!a)return;
   const href=a.getAttribute('href');
   if(href?.startsWith('#')&&!event.defaultPrevented){
    const target=root.getElementById(href.slice(1));if(target){event.preventDefault();target.scrollIntoView({behavior:matchMedia('(prefers-reduced-motion: reduce)').matches?'auto':'smooth'});}
   }
   host.dispatchEvent(new CustomEvent('mashini365:link',{bubbles:true,composed:true,detail:{href:a.href}}));
  });
  host.dataset.m365State='ready';
  host.dispatchEvent(new CustomEvent('mashini365:ready',{bubbles:true,composed:true}));
 }catch(error){fail(host,error);}
}
window.Mashini365Landing=window.Mashini365Landing||{mount};
const start=()=>document.querySelectorAll('[data-m365-landing]').forEach(mount);
if(document.readyState==='loading')document.addEventListener('DOMContentLoaded',start,{once:true});else start();
})(document.currentScript);
`;
await fs.mkdir(path.join(repo,'public/mashini365'),{recursive:true});
await fs.writeFile(path.join(repo,'public/mashini365/landing.js'),bundle);
console.log('Built landing.js:',Buffer.byteLength(bundle),'bytes;',data.length,'products');
